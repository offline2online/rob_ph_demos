'use strict';
// Bundles src/ (everything except http, fs and the token code) into frontend/local-api.js, so the page runs the real
// route handlers in the browser over the one test retailer. A tiny CommonJS shim stands in for require(), and the route
// list is explicit (no directory scan, which needs fs). `npm run build:local-api` writes the file; test/local-api.test.js
// rebuilds it in memory and fails if the committed copy differs.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'frontend', 'local-api.js');

const MODULES = [
  'src/constants.js', 'src/calc/index.js', 'src/filters.js', 'src/scope.js', 'src/dealing.js', 'src/query.js', 'src/store.js',
  'src/aggregate.js', 'src/testdata.js', 'src/advertiser-view.js', 'src/display-types.js', 'src/auth-types.js', 'src/dispatch.js',
];
const ROUTES = [
  'advertisers', 'audience', 'deals-by-display-type', 'deals', 'delivery', 'display-types', 'filter-options', 'health', 'maturity',
  'missed-revenue', 'my-summary', 'my-targeting', 'params', 'revenue', 'slot-allocation', 'slot-value', 'summary', 'yield',
].map((r) => `src/routes/${r}.js`);
const ROUTE_PATHS = ROUTES.filter((r) => !r.endsWith('/params.js'));

function build() {
  const files = [...MODULES, ...ROUTES];
  const defs = files.map((f) => {
    const src = fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/\r\n/g, '\n').replace(/^'use strict';\n/, '');
    return `  ${JSON.stringify(f)}: function (module, exports, require) {\n${src.replace(/\n$/, '')}\n  }`;
  });
  return `// GENERATED by scripts/build-local-api.js (npm run build:local-api) from src/. Do not edit: test/local-api.test.js fails when this differs.
// The real Retail Media Insights route handlers, request dispatch and test retailer, for the page to call in the browser.
//   LocalApi.get(path, params, principal) -> Promise<body>; rejects with {status, error}.
// This is a prototype stand-in for the HTTP API and its login: the principal is chosen by the page, never read from a token.
(function (root) {
  'use strict';
  var DEFS = {
${defs.join(',\n')}
  };
  var cache = {};
  function dirname(p) { var i = p.lastIndexOf('/'); return i < 0 ? '' : p.slice(0, i); }
  function resolve(from, req) {
    var parts = dirname(from).split('/').filter(Boolean);
    req.split('/').forEach(function (seg) { if (seg === '..') parts.pop(); else if (seg !== '.' && seg) parts.push(seg); });
    var base = parts.join('/');
    return [base + '.js', base + '/index.js', base].filter(function (k) { return DEFS[k]; })[0];
  }
  function load(file) {
    if (cache[file]) return cache[file].exports;
    var module = { exports: {} };
    cache[file] = module;
    DEFS[file](module, module.exports, function (req) {
      var key = resolve(file, req);
      if (!key) throw new Error('local-api: cannot find ' + req + ' from ' + file);
      return load(key);
    });
    return module.exports;
  }
  var ROUTE_FILES = ${JSON.stringify(ROUTE_PATHS)};
  var state = null;
  function init() {
    if (state) return state;
    var data = load('src/testdata.js').generateTestRetailer();
    var store = new (load('src/store.js').AggregateStore)(load('src/aggregate.js').buildAggregates(data.raw, data.ctx));
    var routes = ROUTE_FILES.map(load);
    var lastDay = data.raw.billing.reduce(function (m, b) { return b.date > m ? b.date : m; }, '');
    state = { store: store, routes: routes, today: lastDay };
    return state;
  }
  function query(params) {
    var qs = new URLSearchParams();
    Object.keys(params || {}).forEach(function (k) {
      var v = params[k];
      if (v === undefined || v === null) return;
      if (Array.isArray(v)) v.forEach(function (x) { qs.append(k + '[]', x); }); else qs.append(k, v);
    });
    var s = qs.toString();
    return s ? '?' + s : '';
  }
  var LocalApi = {
    BASE: load('src/dispatch.js').BASE,
    // The first test advertiser: the default for the page's ?role=advertiser view.
    firstAdvertiserId: function () { return Object.keys(init().store.advertisers)[0]; },
    get: function (path, params, principal) {
      return new Promise(function (resolveP, rejectP) {
        var s = init();
        var out = load('src/dispatch.js').dispatch({ store: s.store, routes: s.routes, url: LocalApi.BASE + path + query(params), principal: principal || null, today: s.today });
        if (out.status !== 200) return rejectP({ status: out.status, error: out.body && out.body.error });
        resolveP(JSON.parse(JSON.stringify(out.body)));
      });
    }
  };
  root.LocalApi = LocalApi;
  if (typeof module === 'object' && module.exports) module.exports = LocalApi;
})(typeof self !== 'undefined' ? self : globalThis);
`;
}

if (require.main === module) {
  fs.writeFileSync(OUT, build());
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}

module.exports = { build, OUT };
