// Self-hosted fonts for the screen: downloads them ONCE, at build time, from Google Fonts and writes them
// into the page's own stylesheets as data: URLs, so a screen behind a firewall never calls Google at runtime.
//
//   node tools/fetch-fonts.mjs        (rewrites css/fonts.css and css/material-symbols.css)
//
// What is kept, and why:
//   css/fonts.css             Figtree 400-800 (variable, latin + latin-ext): the screen's typeface.
//                             Roboto 400-700 (variable, latin): the platform font, used by the debug panel only.
//   css/material-symbols.css  Material Symbols Outlined, the one instance the screen draws (FILL 1, wght 500,
//                             opsz 24, GRAD 0; every icon). It is a static font, so it is registered for every
//                             weight and the screen's font-variation-settings have nothing to vary.
// Both fonts are open source (Figtree, Roboto: SIL Open Font License 1.1; Material Symbols: Apache 2.0).
// data: URLs keep this a plain text file (the board's patch hand-over takes text only) and need no extra
// request or server MIME type on the Android player.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// A desktop Chrome user agent: Google Fonts then answers with woff2.
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

async function text(url) {
  const r = await fetch(url, { headers: { 'user-agent': UA } });
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r.text();
}
async function b64(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return Buffer.from(await r.arrayBuffer()).toString('base64');
}

// Google's css2 answer -> [{subset, range, url}]
async function faces(family) {
  const css = await text(`https://fonts.googleapis.com/css2?family=${family}&display=block`);
  const out = [];
  const re = /(?:\/\*\s*([\w-]+)\s*\*\/\s*)?@font-face\s*\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const body = m[2];
    const url = (/src:\s*url\(([^)]+)\)/.exec(body) || [])[1];
    const range = (/unicode-range:\s*([^;]+);/.exec(body) || [])[1] || '';
    if (url) out.push({ subset: m[1] || '', range: range.trim(), url });
  }
  if (!out.length) throw new Error(`no @font-face for ${family}`);
  return out;
}

async function familyCss(name, family, subsets, weight) {
  const all = await faces(family);
  const pick = subsets ? all.filter((f) => subsets.includes(f.subset)) : all;
  if (!pick.length) throw new Error(`${name}: none of ${subsets} in ${all.map((f) => f.subset)}`);
  const parts = [];
  for (const f of pick) {
    parts.push(`/* ${name}${f.subset ? ' ' + f.subset : ''} */\n@font-face{font-family:"${name}";font-style:normal;font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${await b64(f.url)}) format("woff2")${f.range ? `;unicode-range:${f.range}` : ''}}`);
  }
  return parts.join('\n');
}

const header = (what) => `/* ${what}\n   Generated by tools/fetch-fonts.mjs from Google Fonts at build time; never fetched at runtime. Do not edit by hand. */\n`;

const fontsCss = header('Self-hosted fonts: Figtree (the screen; SIL OFL 1.1) and Roboto (the debug panel; SIL OFL 1.1).')
  + await familyCss('Figtree', 'Figtree:wght@400..800', ['latin', 'latin-ext'], '400 800') + '\n'
  + await familyCss('Roboto', 'Roboto:wght@400..700', ['latin'], '400 700') + '\n';
fs.writeFileSync(path.join(ROOT, 'css/fonts.css'), fontsCss);

const iconsCss = header('Self-hosted icons: Material Symbols Outlined, FILL 1, wght 500, opsz 24 (Apache 2.0).')
  + await familyCss('Material Symbols Outlined', 'Material+Symbols+Outlined:opsz,wght,FILL,GRAD@24,500,1,0', null, '100 900') + '\n';
fs.writeFileSync(path.join(ROOT, 'css/material-symbols.css'), iconsCss);

console.log(`css/fonts.css ${(fontsCss.length / 1024).toFixed(0)} KB, css/material-symbols.css ${(iconsCss.length / 1024).toFixed(0)} KB`);
